package ie.atu;

public class Calculator {

    public int add(int a, int b) {
        return a + b;
    }

    public int sub(int i, int i1) {
        return i - i1;
    }

    public int mul(int i, int i1) {
        return i * i1;
    }

    public int div(int i, int i1) {
        return i / i1;
    }
}
